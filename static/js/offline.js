// === OFFLINE MODE & STORAGE ===

// Service Worker registration for offline support
if ('serviceWorker' in navigator) {
    window.addEventListener('load', () => {
        navigator.serviceWorker.register('/sw.js').catch(() => {
            console.log('Service Worker registration failed - offline mode limited');
        });
    });
}

// Offline detection
let isOnline = navigator.onLine;

window.addEventListener('online', () => {
    isOnline = true;
    showOnlineStatus('Online - Syncing data...');
    syncOfflineData();
});

window.addEventListener('offline', () => {
    isOnline = false;
    showOnlineStatus('Offline Mode - Data saved locally', 'warning');
});

function showOnlineStatus(message, type = 'success') {
    const toast = document.createElement('div');
    toast.className = `toast toast-${type}`;
    toast.innerHTML = `<i class="fas fa-wifi"></i> ${message}`;
    document.body.appendChild(toast);

    setTimeout(() => toast.classList.add('show'), 100);
    setTimeout(() => {
        toast.classList.remove('show');
        setTimeout(() => toast.remove(), 300);
    }, 3000);
}

// Save scan data offline
function saveOfflineScan(data) {
    const offlineScans = JSON.parse(localStorage.getItem('offlineScans') || '[]');
    offlineScans.push({
        ...data,
        timestamp: Date.now(),
        synced: false
    });
    localStorage.setItem('offlineScans', JSON.stringify(offlineScans));
}

// Sync offline data when online
function syncOfflineData() {
    const offlineScans = JSON.parse(localStorage.getItem('offlineScans') || '[]');
    const unsynced = offlineScans.filter(scan => !scan.synced);

    if (unsynced.length > 0) {
        // Mark as synced
        offlineScans.forEach(scan => scan.synced = true);
        localStorage.setItem('offlineScans', JSON.stringify(offlineScans));
        showOnlineStatus(`Synced ${unsynced.length} scans`, 'success');
    }
}

