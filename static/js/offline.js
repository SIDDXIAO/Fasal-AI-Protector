// Voice search in history
function voiceSearchHistory() {
    if (!('webkitSpeechRecognition' in window)) {
        alert('Voice search not supported');
        return;
    }

    const recognition = new webkitSpeechRecognition();
    recognition.lang = getVoiceLang();

    recognition.onresult = (event) => {
        const query = event.results[0][0].transcript.toLowerCase();
        searchHistory(query);
    };

    recognition.start();
}

// Search history function
function searchHistory(query) {
    const cards = document.querySelectorAll('.history-card');
    let found = 0;

    cards.forEach(card => {
        const title = card.getAttribute('data-title').toLowerCase();
        const date = card.getAttribute('data-date').toLowerCase();
        const status = card.getAttribute('data-status');

        const matches = title.includes(query) ||
            date.includes(query) ||
            (query.includes('healthy') && status === 'safe') ||
            (query.includes('infected') && status === 'danger') ||
            (query.includes('स्वस्थ') && status === 'safe') ||
            (query.includes('संक्रमित') && status === 'danger');

        if (matches) {
            card.style.display = 'flex';
            found++;
        } else {
            card.style.display = 'none';
        }
    });

    if (found === 0) {
        showOnlineStatus('No results found', 'warning');
    } else {
        showOnlineStatus(`Found ${found} results`, 'success');
    }
}

// Clear search
function clearHistorySearch() {
    const cards = document.querySelectorAll('.history-card');
    cards.forEach(card => card.style.display = 'flex');
}
