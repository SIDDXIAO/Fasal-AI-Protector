// Export history as PDF
async function exportHistoryPDF() {
    const { jsPDF } = window.jspdf;
    if (!jsPDF) {
        alert('PDF library not loaded. Please refresh the page.');
        return;
    }
    const doc = new jsPDF();

    // Title
    doc.setFontSize(20);
    doc.setTextColor(0, 176, 155);
    doc.text('FasAi protector - Scan History Report', 20, 20);

    // Date
    doc.setFontSize(10);
    doc.setTextColor(100);
    doc.text(`Generated: ${new Date().toLocaleString()}`, 20, 30);

    // User info
    const userName = document.getElementById('user-display-name').innerText;
    doc.text(`Farmer: ${userName}`, 20, 35);

    // Line separator
    doc.setDrawColor(0, 176, 155);
    doc.line(20, 40, 190, 40);

    // Summary stats
    doc.setFontSize(12);
    doc.setTextColor(0);
    doc.text('Summary Statistics:', 20, 50);

    doc.setFontSize(10);
    const totalScans = stats.total;
    const healthyScans = stats.healthy;
    const infectedScans = stats.infected;
    const healthPercent = ((healthyScans / totalScans) * 100).toFixed(1);

    doc.text(`Total Scans: ${totalScans}`, 30, 60);
    doc.text(`Healthy: ${healthyScans} (${healthPercent}%)`, 30, 67);
    doc.text(`Infected: ${infectedScans} (${(100 - healthPercent).toFixed(1)}%)`, 30, 74);

    // History details
    doc.setFontSize(12);
    doc.text('Recent Scan History:', 20, 90);

    // Get history cards
    const historyCards = document.querySelectorAll('.history-card');
    let yPos = 100;

    historyCards.forEach((card, index) => {
        if (index >= 10) return; // Limit to 10 entries
        if (yPos > 270) {
            doc.addPage();
            yPos = 20;
        }

        const title = card.getAttribute('data-title') || 'Unknown';
        const date = card.getAttribute('data-date') || 'N/A';
        const status = card.getAttribute('data-status') === 'safe' ? 'Healthy' : 'Infected';

        doc.setFontSize(10);
        doc.setTextColor(0);
        doc.text(`${index + 1}. ${title}`, 30, yPos);
        doc.setTextColor(100);
        doc.setFontSize(8);
        doc.text(`   Date: ${date}`, 30, yPos + 5);
        doc.text(`   Status: ${status}`, 30, yPos + 10);

        yPos += 20;
    });

    // Footer
    const pageCount = doc.internal.getNumberOfPages();
    for (let i = 1; i <= pageCount; i++) {
        doc.setPage(i);
        doc.setFontSize(8);
        doc.setTextColor(150);
        doc.text(`Page ${i} of ${pageCount}`, 105, 290, { align: 'center' });
        doc.text('Generated by FasAi protector', 105, 295, { align: 'center' });
    }

    // Save PDF
    doc.save(`FasAi_Report_${Date.now()}.pdf`);

    // Show success message
    const successMsg = typeof t === 'function' ? t('exportSuccess') : 'PDF exported successfully!';
    showOnlineStatus(successMsg, 'success');
    if (typeof confetti === 'function') {
        confetti({ particleCount: 100, spread: 70, origin: { y: 0.6 } });
    }
}

// Export single scan as PDF
async function exportScanPDF(title, img, status, remedy, date) {
    const { jsPDF } = window.jspdf;
    const doc = new jsPDF();

    // Title
    doc.setFontSize(18);
    doc.setTextColor(0, 176, 155);
    doc.text('Scan Analysis Report', 105, 20, { align: 'center' });

    // Date
    doc.setFontSize(10);
    doc.setTextColor(100);
    doc.text(date, 105, 28, { align: 'center' });

    // Status badge
    doc.setFontSize(12);
    if (status === 'safe') {
        doc.setTextColor(0, 176, 155);
        doc.text('✓ HEALTHY', 105, 38, { align: 'center' });
    } else {
        doc.setTextColor(229, 57, 53);
        doc.text('⚠ INFECTED', 105, 38, { align: 'center' });
    }

    // Disease name
    doc.setFontSize(14);
    doc.setTextColor(0);
    doc.text(title, 105, 48, { align: 'center' });

    // Add image (if possible - base64 required)
    try {
        if (img && img.startsWith('data:')) {
            doc.addImage(img, 'JPEG', 55, 55, 100, 75);
        }
    } catch (e) {
        console.log('Image not added to PDF');
    }

    // Remedy section
    doc.setFontSize(12);
    doc.setTextColor(0, 176, 155);
    doc.text('Recommended Treatment:', 20, 140);

    doc.setFontSize(10);
    doc.setTextColor(0);

    // Parse remedy JSON if available
    try {
        const remedyData = JSON.parse(remedy);
        let yPos = 150;

        remedyData.forEach(section => {
            if (yPos > 270) {
                doc.addPage();
                yPos = 20;
            }

            doc.setFontSize(11);
            doc.setTextColor(0, 176, 155);
            doc.text(`${section.icon} ${section.heading}`, 25, yPos);

            doc.setFontSize(9);
            doc.setTextColor(0);
            yPos += 7;

            section.points.forEach(point => {
                const lines = doc.splitTextToSize(`• ${point}`, 160);
                doc.text(lines, 30, yPos);
                yPos += lines.length * 5;
            });

            yPos += 5;
        });
    } catch (e) {
        // Plain text remedy
        const lines = doc.splitTextToSize(remedy, 170);
        doc.text(lines, 20, 150);
    }

    // Footer
    doc.setFontSize(8);
    doc.setTextColor(150);
    doc.text('Generated by FasAi protector', 105, 290, { align: 'center' });

    doc.save(`Scan_${title.replace(/\s+/g, '_')}_${Date.now()}.pdf`);
    showOnlineStatus('Scan exported as PDF', 'success');
    if (typeof confetti === 'function') {
        confetti({ particleCount: 50, spread: 60, origin: { y: 0.7 } });
    }
}

